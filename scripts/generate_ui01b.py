#!/usr/bin/env python3
"""Generate shared native/browser design data, with deterministic check mode."""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
tokens = json.loads((ROOT / 'design/ui01b-tokens.json').read_text())
scene = {}
rows = ',\n'.join('    ModuleSpec(' + json.dumps(m['name'], ensure_ascii=False) + ', ' + json.dumps(m['short'], ensure_ascii=False) + ', 0xFF' + m['color'][1:] + ')' for m in tokens['modules'])
kotlin = '''// Generated by scripts/generate_ui01b.py. Edit design/ui01b-tokens.json.
package com.jarvis.interfaceapp.cockpit

data class ModuleSpec(val name: String, val shortName: String, val argb: Long)
val cockpitModules = listOf(
''' + rows + '\n)\n'
outputs = {
    'app/src/main/java/com/jarvis/interfaceapp/cockpit/CockpitPalette.kt': kotlin,
    'app/src/main/assets/cockpit-scene.json': json.dumps(scene, ensure_ascii=False, separators=(',', ':')) + '\n',
    'preview/design-data.js': 'window.JARVIS_DESIGN = ' + json.dumps({'tokens': tokens, 'scene': scene}, ensure_ascii=False, separators=(',', ':')) + ';\n'
}
for relative, content in outputs.items():
    path = ROOT / relative
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit('Stale generated design: ' + relative)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
print('Shared native/browser design is consistent.')
